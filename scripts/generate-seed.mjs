// Turns src/data/catalog.json into db/seed.sql for Cloudflare D1.
//
//   npm run db:seed:generate
//   wrangler d1 execute game-pedia --remote --file=db/seed.sql
//
// The seed is idempotent: every insert replaces the row with the same id.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(await readFile(join(root, 'src', 'data', 'catalog.json'), 'utf8'));

const q = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  if (typeof v === 'boolean') return v ? '1' : '0';
  return `'${String(v).replace(/'/g, "''")}'`;
};

const json = (v) => (v === null || v === undefined ? 'NULL' : q(JSON.stringify(v)));

const GAME_COLUMNS = [
  'id', 'slug', 'title', 'short_description', 'about', 'developer', 'publisher',
  'release_date', 'genres', 'tags', 'features', 'hero_image', 'box_image',
  'rating', 'price_display', 'featured', 'platforms_released', 'game_modes',
  'esrb_rating', 'engine', 'series', 'metacritic_score', 'steam_reviews_label',
  'player_count', 'main_story_hours', 'completionist_hours', 'awards', 'trivia',
];

const JSON_COLUMNS = new Set([
  'genres', 'tags', 'features', 'platforms_released', 'game_modes', 'awards', 'trivia',
]);

const gameRow = (g) =>
  '(' +
  GAME_COLUMNS.map((c) =>
    JSON_COLUMNS.has(c) ? json(g[c]) : q(g[c])
  ).join(', ') +
  ')';

const lines = [
  '-- Generated by scripts/generate-seed.mjs. Do not edit by hand.',
  `-- Source: ${catalog.source ?? 'unknown'} @ ${catalog.generated_at ?? 'unknown'}`,
  '-- D1 does not allow BEGIN/COMMIT in executed files; the seed is idempotent.',
  'DELETE FROM game_prices;',
  'DELETE FROM games;',
  'DELETE FROM platforms;',
];

if (catalog.platforms?.length) {
  lines.push(
    'INSERT INTO platforms (id, name, slug, color) VALUES\n' +
      catalog.platforms
        .map((p) => `(${q(p.id)}, ${q(p.name)}, ${q(p.slug)}, ${q(p.color)})`)
        .join(',\n') +
      ';'
  );
}

const games = catalog.games ?? [];
for (let i = 0; i < games.length; i += 10) {
  const chunk = games.slice(i, i + 10);
  lines.push(
    `INSERT INTO games (${GAME_COLUMNS.join(', ')}) VALUES\n` +
      chunk.map(gameRow).join(',\n') +
      ';'
  );
}

for (const g of games) {
  const prices = g.game_prices ?? [];
  for (let i = 0; i < prices.length; i += 25) {
    const chunk = prices.slice(i, i + 25);
    lines.push(
      'INSERT INTO game_prices (id, game_id, platform_id, price, regular_price, currency, store_url, product_url, on_sale, updated_at) VALUES\n' +
        chunk
          .map(
            (p) =>
              `(${q(p.id)}, ${q(g.id)}, ${q(p.platform_id)}, ${q(p.price)}, ${q(
                p.regular_price
              )}, ${q(p.currency)}, ${q(p.store_url)}, ${q(p.product_url ?? null)}, ${q(
                p.on_sale
              )}, ${q(p.updated_at ?? null)})`
          )
          .join(',\n') +
        ';'
    );
  }
}

lines.push(
  `INSERT INTO catalog_meta (key, value) VALUES ('generated_at', ${q(
    catalog.generated_at
  )}) ON CONFLICT (key) DO UPDATE SET value = excluded.value;`,
  `INSERT INTO catalog_meta (key, value) VALUES ('source', ${q(
    catalog.source
  )}) ON CONFLICT (key) DO UPDATE SET value = excluded.value;`
);

if (catalog.prices_updated_at) {
  lines.push(
    `INSERT INTO catalog_meta (key, value) VALUES ('prices_updated_at', ${q(
      catalog.prices_updated_at
    )}) ON CONFLICT (key) DO UPDATE SET value = excluded.value;`
  );
}

await writeFile(join(root, 'db', 'seed.sql'), lines.join('\n') + '\n');

const priceCount = games.reduce((n, g) => n + (g.game_prices?.length ?? 0), 0);
console.log(
  `Wrote db/seed.sql: ${games.length} games, ${priceCount} prices, ${catalog.platforms?.length ?? 0} platforms`
);
